#!/bin/bash

if [[ $# -ne 6 ]]; then
    echo "Ошибка: неверное количество параметров"
    echo "Использование: $0 <путь> <количество_папок> <буквы_папок> <количество_файлов> <буквы_файлов.расширение> <размер_файлов>"
    echo "Пример: ./main.sh /opt/test 4 az 5 az.az 3kb"
    exit 1
fi

BASE_PATH="$1"
DIR_NUMBER="$2"
DIR_LETTERS="$3"
FILES_NUMBER="$4"
FILE_LETTERS="$5"
FILE_SIZE="$6"

[[ "$BASE_PATH" = /* ]] || { echo "Ошибка: путь должен быть абсолютным"; exit 1; }
[[ -d "$BASE_PATH" ]] || { echo "Ошибка: путь не существует"; exit 1; }

[[ "$DIR_NUMBER" =~ ^[1-9][0-9]*$ ]] || { echo "Ошибка: неверное количество папок"; exit 1; }
[[ "$DIR_LETTERS" =~ ^[a-zA-Z]{1,7}$ ]] || { echo "Ошибка: неверные буквы для папок"; exit 1; }

[[ "$FILES_NUMBER" =~ ^[1-9][0-9]*$ ]] || { echo "Ошибка: неверное количество файлов"; exit 1; }
[[ "$FILE_LETTERS" =~ ^[a-zA-Z]{1,7}\.[a-zA-Z]{1,3}$ ]] || { echo "Ошибка: неверный формат параметра 5"; exit 1; }

[[ "$FILE_SIZE" =~ ^([1-9][0-9]?|100)kb$ ]] || { echo "Ошибка: размер файла должен быть от 1 до 100kb"; exit 1; }

source ./generator.sh
generate