#!/bin/bash

# проверка на 1 параметр
if [ $# -ne 1 ]
then
echo "Ошибка: необходимо передать 1 параметр"
echo "Пример: $0 параметр"
exit 1
fi

#проверка на число
#if [[ $1 =~ [0-9] ]]
if [[ $1 =~ ^[+-]?([0-9]+[.,]?[0-9]*|[.,][0-9]+) ]]
then
echo "Ошибка: параметр должен быть не числом."
exit 1
fi

echo "$1"