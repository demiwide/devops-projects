#!/bin/bash

# проверка на 1 параметр
if [ $# -ne 1 ]
then
echo "Ошибка: необходимо передать 1 параметр"
echo "Пример: $0 /var/log/"
exit 1
fi

#проверка окончания на /
if [[ ! "$1" =~ /$ ]]; then
echo "Ошибка: параметр должен заканчиваться символом '/'"
echo "Пример: $0 /var/log/"
exit 1
fi

if [ ! -d "$1" ]
then
echo "Ошибка: указанного каталога не существует"
exit 1
fi

source "./info.sh"